#!/usr/bin/env node
/*
 * Exports the Blockbench projects in blockbench/*.bbmodel into the mod, using Blockbench itself
 * (the web app, driven by a headless Chromium through Playwright):
 *
 *   Modded Entity projects -> src/client/java/ru/winter/client/render/model/<Name>ModelData.java
 *                             (geometry from Blockbench's "Java Entity (1.17+)" export, Mojang names)
 *                             + the project's texture -> assets/winter/textures/entity/<name>.png
 *   Java Block projects    -> assets/winter/models/block/<name>.json (Blockbench's "Java Block/Item" export)
 *   every project          -> docs/models/<name>.png preview render, and the .bbmodel is re-saved by Blockbench
 *
 * Usage:   node tools/blockbench_export.js [model names...]
 * Needs:   Node.js and Playwright with Chromium (npm i -g playwright && npx playwright install chromium).
 * Env:     BLOCKBENCH_URL (default https://web.blockbench.net/)
 *
 * The same files can be produced by hand in the Blockbench app: File > Export > "Export Java Entity" /
 * "Export Block/Item Model".
 */
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '..');
const BB_DIR = path.join(ROOT, 'blockbench');
const ASSETS = path.join(ROOT, 'src/main/resources/assets/winter');
const JAVA_DIR = path.join(ROOT, 'src/client/java/ru/winter/client/render/model');
const DOCS = path.join(ROOT, 'docs/models');
const URL = process.env.BLOCKBENCH_URL || 'https://web.blockbench.net/';

const pascal = s => s.split('_').map(p => p[0].toUpperCase() + p.slice(1)).join('');
const write = (file, data) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
  console.log('  wrote', path.relative(ROOT, file));
};

function javaModelData(name, java, bbVersion) {
  const method = java.match(/\tpublic static LayerDefinition createBodyLayer\(\) \{[\s\S]*?\n\t\}/);
  if (!method) throw new Error(`No createBodyLayer() in the export of ${name}`);
  return `// Generated by tools/blockbench_export.js from blockbench/${name}.bbmodel
// with Blockbench ${bbVersion} ("Modded Entity" export for Minecraft 1.17+, Mojang mappings).
// Do not edit: change the model in Blockbench and run the export again.
package ru.winter.client.render.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

@SuppressWarnings("unused")
public final class ${pascal(name)}ModelData {
\tprivate ${pascal(name)}ModelData() {
\t}

${method[0]}
}
`;
}

async function exportModel(browser, file) {
  const name = path.basename(file, '.bbmodel');
  console.log(`${name}:`);
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  page.on('pageerror', e => console.log('  [blockbench error]', e.message));
  await page.goto(URL, { waitUntil: 'load', timeout: 180000 });
  await page.waitForFunction(() => typeof Codecs !== 'undefined' && typeof loadModelFile === 'function', null, { timeout: 180000 });

  const content = fs.readFileSync(file, 'utf8');
  const result = await page.evaluate(({ content, name }) => {
    loadModelFile({ path: `${name}.bbmodel`, name: `${name}.bbmodel`, content });
    // Box-UV cubes generated without faces: give every face the (single) entity texture.
    if (Format.id === 'modded_entity' && Texture.all.length) {
      Cube.all.forEach(c => {
        for (const f in c.faces) if (!c.faces[f].texture) c.faces[f].texture = Texture.all[0].uuid;
      });
    }
    Canvas.updateAll();
    const out = { format: Format.id, version: Blockbench.version, project: Codecs.project.compile() };
    if (Format.id === 'modded_entity') {
      Project.modded_entity_version = '1.17';
      out.java = Codecs.modded_entity.compile();
      out.textures = Texture.all.map(t => ({ name: t.name, folder: t.folder, data: t.getDataURL() }));
    } else if (Format.id === 'java_block') {
      out.json = Codecs.java_block.compile();
    }
    // frame the model for the preview render
    let min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
    Cube.all.forEach(c => {
      for (let i = 0; i < 3; i++) {
        min[i] = Math.min(min[i], c.from[i]);
        max[i] = Math.max(max[i], c.to[i]);
      }
    });
    if (Format.id === 'java_block') {
      min = min.map((v, i) => i === 1 ? v : v - 8);
      max = max.map((v, i) => i === 1 ? v : v - 8);
    }
    const center = min.map((v, i) => (v + max[i]) / 2);
    const size = Math.max(...max.map((v, i) => v - min[i]));
    const preview = Preview.selected;
    const dist = size * 2.1;
    preview.camera.position.set(center[0] + dist * 0.55, center[1] + dist * 0.35, center[2] - dist * 0.8);
    preview.controls.target.set(center[0], center[1], center[2]);
    preview.controls.update();
    const r = preview.canvas.getBoundingClientRect();
    out.clip = { x: r.x, y: r.y, width: r.width, height: r.height };
    return out;
  }, { content, name });

  write(file, JSON.stringify(JSON.parse(result.project), null, '\t') + '\n');
  if (result.format === 'modded_entity') {
    write(path.join(JAVA_DIR, `${pascal(name)}ModelData.java`), javaModelData(name, result.java, result.version));
    for (const t of result.textures) {
      write(path.join(ASSETS, 'textures', t.folder || 'entity', t.name),
        Buffer.from(t.data.split(',')[1], 'base64'));
    }
  } else if (result.format === 'java_block') {
    const json = typeof result.json === 'string' ? JSON.parse(result.json) : result.json;
    // Blockbench 5.2 leaves out the per-element "shade": false flag; restore it from the project.
    const project = JSON.parse(result.project);
    const unshaded = new Set(project.elements.filter(e => e.shade === false).map(e => e.name));
    for (const e of json.elements || []) if (unshaded.has(e.name)) e.shade = false;
    write(path.join(ASSETS, 'models/block', `${name}.json`), JSON.stringify(json, null, '\t') + '\n');
  } else {
    throw new Error(`${name}: unexpected format ${result.format}`);
  }
  await page.waitForTimeout(1500);
  fs.mkdirSync(DOCS, { recursive: true });
  await page.screenshot({ path: path.join(DOCS, `${name}.png`), clip: result.clip });
  console.log('  wrote', path.relative(ROOT, path.join(DOCS, `${name}.png`)));
  await page.close();
  return result.version;
}

(async () => {
  const only = process.argv.slice(2);
  const files = fs.readdirSync(BB_DIR).filter(f => f.endsWith('.bbmodel'))
    .filter(f => !only.length || only.includes(path.basename(f, '.bbmodel')))
    .map(f => path.join(BB_DIR, f));
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  let version;
  for (const file of files) version = await exportModel(browser, file);
  await browser.close();
  console.log(`Exported ${files.length} models with Blockbench ${version}`);
})().catch(e => {
  console.error(e);
  process.exit(1);
});
